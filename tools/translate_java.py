def translate_java_files():
    total_updated = 0
    for root, dirs, files in os.walk('app/src/main/java'):
        for file in files:
            if file in FILE_REPLACEMENTS:
                filepath = os.path.normpath(os.path.join(root, file))
                with open(filepath, 'r', encoding='utf-8', newline='') as f:
                    content = f.read()
                orig_content = content
                for old, new in FILE_REPLACEMENTS[file]:
                    old_crlf = old.replace('\n', '\r\n')
                    old_lf = old.replace('\r\n', '\n')
                    if old in content:
                        content = content.replace(old, new)
                    elif old_crlf in content:
                        content = content.replace(old_crlf, new.replace('\n', '\r\n'))
                    elif old_lf in content:
                        content = content.replace(old_lf, new.replace('\r\n', '\n'))
                    else:
                        print(f"Warning: [{file}] pattern not found: {old[:50]}")
                if content != orig_content:
                    with open(filepath, 'w', encoding='utf-8', newline='') as f:
                        f.write(content)
                    total_updated += 1
                    print(f"Updated: {filepath}")

    print(f"\nTotal Java files updated: {total_updated}")

if __name__ == '__main__':
    translate_java_files()
